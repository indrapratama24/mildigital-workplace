async function reset() {
  // order matters (FKs); append-only tables need their triggers disabled for a full reset
  await db.$executeRawUnsafe(`ALTER TABLE "ApprovalAction" DISABLE TRIGGER USER`);
  await db.$executeRawUnsafe(`ALTER TABLE "AuditLog" DISABLE TRIGGER USER`);
  await db.$executeRawUnsafe(`ALTER TABLE "AttendanceCorrection" DISABLE TRIGGER USER`);
  await db.$executeRawUnsafe(`ALTER TABLE "ScheduleVersion" DISABLE TRIGGER USER`);
  const tables = [
    "ApprovalAction", "ApprovalStep", "ApprovalWorkflow", "AuditLog", "Notification", "AttendanceCorrection", "AttendanceRecord",
    "AttendanceException", "ScheduleRevisionItem", "ScheduleRevision", "ScheduleVersion", "ScheduleDay", "MonthlySchedule",
    "DelegationAssignment", "Request", "StoredFile", "LeaveBalance", "RequestType", "Holiday", "HolidayCalendar",
    "EmployeePolicyAssignment", "EmployeeLevelAssignment", "ReportingRelationship", "EmployeeTeamMembership", "Team",
    "EmployeeLevel", "PolicyVersion", "Policy", "Session", "Employee", "Department", "User", "SystemSetting",
    "PermissionGrant", "ClientTeamAssignment", "ClientStatusHistory", "ClientEngagementPackage", "ClientEngagement", "ClientCodeAlias", "ClientBrand",
    "ClientOrganization", "RegulationAcknowledgement", "RegulationVersion", "CompanyRegulation", "AnnouncementAudience", "Announcement", "EmployeeRecognition",
  ];
  await db.$executeRawUnsafe(`TRUNCATE ${tables.map((t) => `"${t}"`).join(", ")} CASCADE`);
  for (const t of ["ApprovalAction", "AuditLog", "AttendanceCorrection", "ScheduleVersion"]) await db.$executeRawUnsafe(`ALTER TABLE "${t}" ENABLE TRIGGER USER`);
  await db.$executeRawUnsafe(`ALTER SEQUENCE "client_code_seq" RESTART WITH 1`);
}

