"use server";
// Schedules, revisions, approvals, attendance
import { revalidatePath } from "next/cache";
import { z } from "zod";
import { requireUser } from "../auth/guard";
import { invalid, runAction } from "../errors";
import { autoGenerateDraft, resetDraft, saveDraft, submitSchedule } from "../services/schedules";
import { cancelRevision, createRevision, previewRevision } from "../services/revisions";
import { clarify, decide, reassign } from "../services/approvals";
import { clockIn, correctRecord, verifyRecords } from "../services/attendance";

const month = z.object({ employeeId: z.string().min(1), year: z.number().int().min(2000).max(2100), month: z.number().int().min(1).max(12) });
const date = z.string().regex(/^\d{4}-\d{2}-\d{2}$/);
const mode = z.enum(["WFO", "WFH"]);

const refresh = () => {
  revalidatePath("/", "layout");
};

export async function saveDraftAction(input: unknown) {
  return runAction(async () => {
    const me = await requireUser();
    const p = month.extend({ modes: z.record(date, mode.nullable()) }).parse(input);
    const ev = await saveDraft(me, p);
    refresh();
    return ev;
  }, "Draft saved");
}

export async function autoGenerateAction(input: unknown) {
  return runAction(async () => {
    const me = await requireUser();
    const p = month.extend({ mode: z.enum(["generate", "balance"]) }).parse(input);
    const ev = await autoGenerateDraft(me, p);
    refresh();
    return ev;
  });
}

export async function resetDraftAction(input: unknown) {
  return runAction(async () => {
    const me = await requireUser();
    await resetDraft(me, month.parse(input));
    refresh();
  }, "Draft reset");
}

export async function submitScheduleAction(input: unknown) {
  return runAction(async () => {
    const me = await requireUser();
    const p = month.extend({ note: z.string().max(500).optional() }).parse(input);
    const r = await submitSchedule(me, p);
    refresh();
    return r;
  });
}

const changes = z.array(z.object({ date, toMode: mode, isReplacement: z.boolean().optional() })).min(1).max(10);

export async function previewRevisionAction(input: unknown) {
  return runAction(async () => {
    const me = await requireUser();
    const p = month.extend({ changes }).parse(input);
    return previewRevision(me, p);
  });
}

export async function createRevisionAction(input: unknown) {
  return runAction(async () => {
    const me = await requireUser();
    const p = month
      .extend({ changes, kind: z.enum(["WFO_TO_WFH", "WFH_TO_WFO", "SWAP", "ADDITIONAL_WFH"]), reason: z.string().max(1000), requestException: z.boolean().optional(), idempotencyKey: z.string().uuid() })
      .parse(input);
    const r = await createRevision(me, p);
    refresh();
    return { id: r.id };
  }, "Change request sent to your leader");
}

export async function cancelRevisionAction(id: string) {
  return runAction(async () => {
    const me = await requireUser();
    await cancelRevision(me, z.string().parse(id));
    refresh();
  }, "Revision cancelled");
}

export async function decideAction(input: unknown) {
  return runAction(async () => {
    const me = await requireUser();
    const p = z.object({ stepId: z.string(), decision: z.enum(["APPROVE", "REJECT", "REQUEST_CHANGES", "ACCEPT", "DECLINE", "REQUEST_CLARIFICATION"]), comment: z.string().max(1000).optional() }).parse(input);
    const r = await decide(me, p.stepId, p.decision, p.comment);
    refresh();
    return r;
  });
}

export async function clarifyAction(input: unknown) {
  return runAction(async () => {
    const me = await requireUser();
    const p = z.object({ stepId: z.string(), comment: z.string().min(1).max(1000) }).parse(input);
    await clarify(me, p.stepId, p.comment);
    refresh();
  }, "Clarification sent");
}

export async function reassignAction(input: unknown) {
  return runAction(async () => {
    const me = await requireUser();
    const p = z.object({ stepId: z.string(), assigneeId: z.string(), reason: z.string().min(5).max(500) }).parse(input);
    await reassign(me, p.stepId, p.assigneeId, p.reason);
    refresh();
  }, "Approval reassigned");
}

export async function clockInAction(input: unknown) {
  return runAction(async () => {
    const me = await requireUser();
    const p = z.object({ mode: z.enum(["WFO", "WFH", "OFFSITE"]), note: z.string().max(280).optional() }).parse(input);
    const r = await clockIn(me, p.mode, p.note);
    refresh();
    return { at: r.clockInAt?.toISOString() };
  }, "Checked in");
}

export async function verifyAttendanceAction(input: unknown) {
  return runAction(async () => {
    const me = await requireUser();
    const p = z.object({ ids: z.array(z.string()).min(1).max(200), status: z.enum(["VERIFIED", "REJECTED"]) }).parse(input);
    const r = await verifyRecords(me, p.ids, p.status);
    refresh();
    return r;
  });
}

export async function correctAttendanceAction(input: unknown) {
  return runAction(async () => {
    const me = await requireUser();
    const p = z
      .object({ employeeId: z.string(), date, mode: z.enum(["WFO", "WFH", "OFFSITE", "NONE"]), verification: z.enum(["VERIFIED", "UNVERIFIED", "REJECTED"]), reason: z.string().max(500) })
      .parse(input);
    if (!p.reason.trim()) throw invalid("Reason is required.");
    await correctRecord(me, p);
    refresh();
  }, "Attendance corrected");
}
