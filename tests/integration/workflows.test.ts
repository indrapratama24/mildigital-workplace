describe("Policy administration and level edits", () => {
  it("renames, blocks removal while in use, archives when history exists, deletes when unused", async () => {
    const { updatePolicyDetails, removePolicy, createPolicy } = await import("@/server/services/admin");
    const admin = await org.actor("admin");
    await expectError(updatePolicyDetails(await org.actor("hr"), { id: org.policies.JUNIOR, name: "X policy", description: null }), "FORBIDDEN");
    await updatePolicyDetails(admin, { id: org.policies.JUNIOR, name: "Junior — 75% (renamed)", description: "Collective M/W/Th" });
    expect((await db.policy.findUniqueOrThrow({ where: { id: org.policies.JUNIOR } })).name).toBe("Junior — 75% (renamed)");
    await expectError(updatePolicyDetails(admin, { id: org.policies.JUNIOR, name: "Principal 50%", description: null }), "CONFLICT");
    // in use by a level → blocked
    await expectError(removePolicy(admin, org.policies.JUNIOR), "CONFLICT", /Junior & Associate/);
    // unused → deleted
    const fresh = await createPolicy(admin, { name: "Temporary 60%", wfoPercent: 60, effectiveFrom: "2026-11-01" });
    expect((await removePolicy(admin, fresh.id)).mode).toBe("deleted");
    expect(await db.policy.findUnique({ where: { id: fresh.id } })).toBeNull();
    // used by a submitted schedule (history) → archived after its level moves away
    await approvedPlan("principal");
    await db.employeeLevel.update({ where: { id: org.levels.PRINCIPAL }, data: { policyId: org.policies.MANAGER } });
    expect((await removePolicy(admin, org.policies.PRINCIPAL)).mode).toBe("archived");
    expect((await db.policy.findUniqueOrThrow({ where: { id: org.policies.PRINCIPAL } })).isActive).toBe(false);
    // the archived version still evaluates November (snapshot)
    expect((await loadMonthContext(org.ids.principal, 2026, 11)).policy?.version.wfoPercent).toBe(50);
  });

  it("level changes on the same date replace the scheduled one instead of failing", async () => {
    const hr = await org.actor("hr");
    await changeLevel(hr, { employeeId: org.ids.junior, levelId: org.levels.PRINCIPAL, effectiveFrom: "2026-12-01", reason: "Moved to IC track" });
    await changeLevel(hr, { employeeId: org.ids.junior, levelId: org.levels.MANAGER, effectiveFrom: "2026-12-01", reason: "Corrected: promoted to lead" });
    const rows = await db.employeeLevelAssignment.findMany({ where: { employeeId: org.ids.junior }, orderBy: { effectiveFrom: "asc" } });
    expect(rows.map((r) => r.levelId)).toEqual([org.levels.JUNIOR, org.levels.MANAGER]);
    expect((await loadMonthContext(org.ids.junior, 2026, 12)).policy?.version.policyId).toBe(org.policies.MANAGER);
    await expectError(changeLevel(hr, { employeeId: org.ids.junior, levelId: org.levels.MANAGER, effectiveFrom: "2026-12-01", reason: "again" }), "VALIDATION", /already/);
  });
});
