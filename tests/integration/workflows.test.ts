describe("Scenario C — additional WFH requires a replacement WFO day", () => {
  it("detects the shortfall, suggests dates, and applies only affected dates", async () => {
    const ctx = await approvedPlan("junior");
    const junior = await org.actor("junior");
    const flex = ctx.requirement!.days.find((d) => d.plannable && !d.mandatory && d.date > "2026-11-03" && ctx.approvedModes[d.date] === "WFO")!;
    const err = await expectError(
      createRevision(junior, { employeeId: junior.employeeId, year: 2026, month: 11, kind: "ADDITIONAL_WFH", changes: [{ date: flex.date, toMode: "WFH" }], reason: "Waiting for a delivery at home", idempotencyKey: key() }),
      "VALIDATION",
      /drop to 15, below the minimum of 16/,
    );
    const impact = (err.details as { impact: { shortfall: number; suggestions: string[] } }).impact;
    expect(impact.shortfall).toBe(1);
    expect(impact.suggestions.length).toBeGreaterThan(0);

    const replacement = impact.suggestions[0];
    await createRevision(junior, {
      employeeId: junior.employeeId, year: 2026, month: 11, kind: "ADDITIONAL_WFH",
      changes: [{ date: flex.date, toMode: "WFH" }, { date: replacement, toMode: "WFO", isReplacement: true }],
      reason: "Waiting for a delivery at home", idempotencyKey: key(),
    });
    const leader = await org.actor("leader");
    await decide(leader, (await pendingStepFor(leader.employeeId))!.id, "APPROVE", "OK");
    const after = await loadMonthContext(junior.employeeId, 2026, 11);
    expect(after.schedule?.status).toBe("APPROVED");
    expect(after.approvedModes[flex.date]).toBe("WFH");
    expect(after.approvedModes[replacement]).toBe("WFO");
    for (const d of Object.keys(ctx.approvedModes)) if (d !== flex.date && d !== replacement) expect(after.approvedModes[d]).toBe(ctx.approvedModes[d]);
    expect(evaluatePlan(after.requirement!, after.approvedModes).plannedWfo).toBe(16);
    const versions = await db.scheduleVersion.findMany({ where: { scheduleId: after.schedule!.id } });
    expect(versions.map((v) => v.kind)).toContain("REVISION_APPLIED");
  });

  it("mandatory-day changes need an authorised exception (leader + HR when configured)", async () => {
    await approvedPlan("junior");
    const junior = await org.actor("junior");
    const input = { employeeId: junior.employeeId, year: 2026, month: 11, kind: "WFO_TO_WFH" as const, changes: [{ date: "2026-11-11", toMode: "WFH" as const }], reason: "Medical check-up in the morning", idempotencyKey: key() };
    await expectError(createRevision(junior, input), "VALIDATION", /exception/);
    const rev = await createRevision(junior, { ...input, requestException: true });
    expect(rev.requiresException).toBe(true);
    const leader = await org.actor("leader");
    await decide(leader, (await pendingStepFor(leader.employeeId))!.id, "APPROVE", "OK by me");
    // Junior policy requires HR for exceptions → second layer
    const hr = await org.actor("hr");
    const hrStep = await pendingStepFor(hr.employeeId);
    expect(hrStep?.kind).toBe("HR");
    await decide(hr, hrStep!.id, "APPROVE", "Exception granted");
    const exceptions = await db.attendanceException.findMany({ where: { employeeId: junior.employeeId } });
    expect(exceptions.map((e) => e.kind).sort()).toEqual(["MANDATORY_DAY_WAIVER", "WFO_REDUCTION"]);
    const after = await loadMonthContext(junior.employeeId, 2026, 11);
    expect(after.requirement!.days.find((d) => d.date === "2026-11-11")?.waived).toBe(true);
    expect(evaluatePlan(after.requirement!, after.approvedModes).compliant).toBe(true);
  });
});

describe("Scenario D — leave with delegation: peer accepts, leader approves", () => {
  const leave = (delegateId: string, start = "2026-12-09", end = "2026-12-10") => ({
    requestTypeId: org.types.ANNUAL, startDate: start, endDate: end, durationType: "FULL_DAY" as const,
    reason: "Family wedding in Yogyakarta",
    delegations: [{ delegateId, handoverNotes: "Monitor ad pacing and send the weekly report", tasks: [{ task: "Weekly report", deadline: end }], coverageStart: start, coverageEnd: end }],
    idempotencyKey: key(),
  });

  it("is sequential, updates calendar, denominator and balance", async () => {
    const decCtxBefore = await loadMonthContext(org.ids.junior, 2026, 12);
    expect(decCtxBefore.requirement!.effectiveMinimumWfo).toBe(17); // 22 eligible days × 75%
    const junior = await org.actor("junior");
    const r = await submitRequest(junior, leave(org.ids.peer));
    expect(r.status).toBe("PENDING_DELEGATE");
    const leader = await org.actor("leader");
    // leader cannot act before the delegate
    expect(await pendingStepFor(leader.employeeId)).toBeNull();
    const peer = await org.actor("peer");
    const dStep = await pendingStepFor(peer.employeeId);
    expect(dStep?.kind).toBe("DELEGATE");
    await expectError(decide(peer, dStep!.id, "APPROVE"), "VALIDATION"); // peers accept coverage, they don't approve leave
    await decide(peer, dStep!.id, "ACCEPT", "Happy to cover");
    expect((await db.request.findUniqueOrThrow({ where: { id: r.id } })).status).toBe("PENDING_LEADER");
    const lStep = await pendingStepFor(leader.employeeId);
    await decide(leader, lStep!.id, "APPROVE", "Enjoy");
    const final = await db.request.findUniqueOrThrow({ where: { id: r.id }, include: { delegations: true } });
    expect(final.status).toBe("APPROVED");
    expect(final.delegations[0]?.status).toBe("ACCEPTED");

    const decCtx = await loadMonthContext(org.ids.junior, 2026, 12);
    expect(decCtx.requirement!.fullLeaveDays).toBe(2);
    expect(decCtx.requirement!.attendanceEligibleDays).toBe(20);
    expect(decCtx.requirement!.effectiveMinimumWfo).toBe(15);
    expect(decCtx.requirement!.days.find((d) => d.date === "2026-12-09")?.kind).toBe("LEAVE");
    const bal = await leaveBalance(db, org.ids.junior, org.types.ANNUAL, 2026);
    expect(bal).toMatchObject({ entitled: 12, used: 2, pending: 0, remaining: 10 });
    const types = (await db.notification.findMany({ where: { userId: junior.userId } })).map((n) => n.type);
    expect(types).toEqual(expect.arrayContaining(["DELEGATION_ACCEPTED", "REQUEST_APPROVED"]));
  });

  it("delegation decline returns the request for a new delegate", async () => {
    const junior = await org.actor("junior");
    const r = await submitRequest(junior, leave(org.ids.peer));
    const peer = await org.actor("peer");
    await expectError(decide(peer, (await pendingStepFor(peer.employeeId))!.id, "DECLINE"), "VALIDATION", /comment/);
    await decide(peer, (await pendingStepFor(peer.employeeId))!.id, "DECLINE", "I'm on a shoot that week");
    const after = await db.request.findUniqueOrThrow({ where: { id: r.id }, include: { delegations: true } });
    expect(after.status).toBe("CHANGES_REQUESTED");
    expect(after.delegations[0]?.status).toBe("DECLINED");
    expect(await pendingStepFor(org.ids.leader)).toBeNull();
    // resubmit with another delegate
    const again = await submitRequest(junior, { ...leave(org.ids.principal), id: r.id });
    expect(again.status).toBe("PENDING_DELEGATE");
    expect((await pendingStepFor(org.ids.principal))?.kind).toBe("DELEGATE");
  });

  it("blocks overlapping requests, circular delegation and unavailable delegates", async () => {
    const junior = await org.actor("junior");
    await submitRequest(junior, leave(org.ids.peer));
    await expectError(submitRequest(junior, leave(org.ids.principal, "2026-12-10", "2026-12-11")), "CONFLICT", /Overlaps/);
    // peer is now covering for junior; peer delegating back to junior for an overlapping period is circular
    const peer = await org.actor("peer");
    await expectError(submitRequest(peer, leave(org.ids.junior, "2026-12-10", "2026-12-10")), "CONFLICT", /circular|leave during/);
    // principal cannot pick junior as delegate while junior is on leave
    await expectError(submitRequest(await org.actor("principal"), leave(org.ids.junior, "2026-12-09", "2026-12-09")), "CONFLICT", /leave during/);
    await expectError(submitRequest(junior, { ...leave(org.ids.junior, "2026-12-14", "2026-12-14") }), "VALIDATION", /yourself/);
  });

  it("supports several delegates: all accept in parallel, then the leader", async () => {
    const junior = await org.actor("junior");
    const two = leave(org.ids.peer);
    two.delegations.push({ delegateId: org.ids.principal, handoverNotes: "Cover the client sync on Thursday", tasks: [], coverageStart: "2026-12-10", coverageEnd: "2026-12-10" });
    const r = await submitRequest(junior, two);
    expect(r.status).toBe("PENDING_DELEGATE");
    // both delegates are asked at once
    const peerStep = await pendingStepFor(org.ids.peer);
    const principalStep = await pendingStepFor(org.ids.principal);
    expect(peerStep?.kind).toBe("DELEGATE");
    expect(principalStep?.kind).toBe("DELEGATE");
    await decide(await org.actor("peer"), peerStep!.id, "ACCEPT", "ok");
    expect((await db.request.findUniqueOrThrow({ where: { id: r.id } })).status).toBe("PENDING_DELEGATE");
    expect(await pendingStepFor(org.ids.leader)).toBeNull(); // leader waits for every delegate
    await decide(await org.actor("principal"), principalStep!.id, "ACCEPT", "ok");
    expect((await db.request.findUniqueOrThrow({ where: { id: r.id } })).status).toBe("PENDING_LEADER");
    await decide(await org.actor("leader"), (await pendingStepFor(org.ids.leader))!.id, "APPROVE");
    const final = await db.request.findUniqueOrThrow({ where: { id: r.id }, include: { delegations: true } });
    expect(final.status).toBe("APPROVED");
    expect(final.delegations.map((d) => d.status)).toEqual(["ACCEPTED", "ACCEPTED"]);
  });

  it("one decline among several delegates withdraws the others and returns the request", async () => {
    const junior = await org.actor("junior");
    const two = leave(org.ids.peer);
    two.delegations.push({ delegateId: org.ids.principal, handoverNotes: "Cover the client sync on Thursday", tasks: [], coverageStart: "2026-12-10", coverageEnd: "2026-12-10" });
    const r = await submitRequest(junior, two);
    await decide(await org.actor("principal"), (await pendingStepFor(org.ids.principal))!.id, "DECLINE", "On a shoot that day");
    const after = await db.request.findUniqueOrThrow({ where: { id: r.id }, include: { delegations: { orderBy: { createdAt: "asc" } } } });
    expect(after.status).toBe("CHANGES_REQUESTED");
    expect(after.delegations.map((d) => d.status).sort()).toEqual(["CANCELLED", "DECLINED"]);
    expect(await pendingStepFor(org.ids.peer)).toBeNull();
    // duplicate delegates are rejected
    const dup = leave(org.ids.peer);
    dup.delegations.push({ ...dup.delegations[0] });
    await expectError(submitRequest(junior, { ...dup, id: r.id }), "VALIDATION", /only be added once/);
  });

  it("requires a delegate for annual leave and allows bypass for sick leave", async () => {
    const junior = await org.actor("junior");
    await expectError(submitRequest(junior, { ...leave(org.ids.peer), delegations: [] }), "VALIDATION", /requires a delegate/);
    const sick = await submitRequest(junior, { requestTypeId: org.types.SICK, startDate: "2026-11-03", endDate: "2026-11-03", durationType: "FULL_DAY", reason: "Migraine", idempotencyKey: key() });
    expect(sick.status).toBe("PENDING_LEADER");
  });
});

