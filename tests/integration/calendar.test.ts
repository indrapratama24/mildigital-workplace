describe("calendar permissions", () => {
  it("employees and leaders can't create events without an explicit grant; Super Admin can", async () => {
    await expectError(createEvent(await org.actor("junior"), base(), true), "FORBIDDEN");
    await expectError(createEvent(await org.actor("leader"), base(), true), "FORBIDDEN"); // team leader ≠ calendar editor
    const r = await createEvent(await org.actor("admin"), base(), true);
    expect(r.occurrences).toBe(1);
  });

  it("scoped editors only manage events for their team; participants never get edit rights", async () => {
    const admin = await org.actor("admin");
    await addCalendarGrant(admin, { subjectType: "EMPLOYEE", subjectId: org.ids.peer, permissionRole: "EDITOR", scope: "TEAM", scopeId: teamId });
    const peer = await org.actor("peer");
    const teamEvent = await createEvent(peer, base({ rules: [{ type: "TEAM", targetId: teamId, dynamic: false }], organizerId: org.ids.peer }), true);
    await expectError(createEvent(peer, base(), true), "FORBIDDEN"); // company-wide needs ALL scope
    await expectError(createEvent(peer, base({ rules: [{ type: "EMPLOYEE", targetId: org.ids.designer, dynamic: false }] }), true), "FORBIDDEN");
    // junior is a participant but not an editor
    await expectError(updateEvent(await org.actor("junior"), teamEvent.id, base({ title: "Hijacked", rules: [{ type: "TEAM", targetId: teamId, dynamic: false }] }), "THIS"), "FORBIDDEN");
    // a team-based grant works too
    await addCalendarGrant(admin, { subjectType: "TEAM", subjectId: otherTeamId, permissionRole: "ORGANIZER", scope: "TEAM", scopeId: otherTeamId });
    await createEvent(await org.actor("designer"), base({ organizerId: org.ids.designer, rules: [{ type: "TEAM", targetId: otherTeamId, dynamic: false }] }), false);
  });
});

describe("participants", () => {
  it("deduplicates people across groups and keeps the most specific source", async () => {
    const r = await createEvent(await org.actor("admin"), base({ rules: [{ type: "ALL", targetId: null, dynamic: false }, { type: "TEAM", targetId: teamId, dynamic: false }, { type: "EMPLOYEE", targetId: org.ids.junior, dynamic: false }] }), true);
    const parts = await db.internalEventParticipant.findMany({ where: { eventId: r.id } });
    expect(parts).toHaveLength(await db.employee.count({ where: { isActive: true } }));
    expect(parts.find((p) => p.employeeId === org.ids.junior)?.assignmentSource).toBe("EMPLOYEE");
    expect(parts.find((p) => p.employeeId === org.ids.designer)?.assignmentSource).toBe("ALL");
  });

  it("is a snapshot by default; refresh or dynamic rules pick up new team members", async () => {
    const admin = await org.actor("admin");
    const snap = await createEvent(admin, base({ rules: [{ type: "TEAM", targetId: otherTeamId, dynamic: false }] }), true);
    const dyn = await createEvent(admin, base({ title: "Dynamic", rules: [{ type: "TEAM", targetId: otherTeamId, dynamic: true }] }), true);
    await db.employeeTeamMembership.create({ data: { employeeId: org.ids.peer, teamId: otherTeamId, isPrimary: false, effectiveFrom: fromISO("2026-11-01") } });
    expect(await db.internalEventParticipant.count({ where: { eventId: snap.id } })).toBe(1);
    await refreshDynamicParticipants();
    expect(await db.internalEventParticipant.count({ where: { eventId: dyn.id } })).toBe(2);
    expect(await db.internalEventParticipant.count({ where: { eventId: snap.id } })).toBe(1);
    const r = await refreshParticipants(admin, snap.id, "THIS");
    expect(r.added).toBe(1);
  });
});

describe("recurring events", () => {
  const weekly = () => base({ title: "Weekly Huddle", date: "2026-11-02", endDate: "2026-11-02", startTime: "13:00", endTime: "14:00", recurrence: { freq: "WEEKLY", interval: 1, byWeekdays: [1], untilDate: "2026-11-30" } });

  it("materialises occurrences and notifies each participant once per series", async () => {
    const r = await createEvent(await org.actor("admin"), weekly(), true);
    expect(r.occurrences).toBe(5);
    const juniorUser = (await db.employee.findUniqueOrThrow({ where: { id: org.ids.junior } })).userId!;
    expect(await db.notification.count({ where: { userId: juniorUser, type: "EVENT_PUBLISHED" } })).toBe(1);
  });

  it("edits this occurrence, this-and-following, and the entire series", async () => {
    const admin = await org.actor("admin");
    const r = await createEvent(admin, weekly(), true);
    const occ = await db.internalEvent.findMany({ where: { seriesId: r.seriesId! }, orderBy: { startAt: "asc" } });
    // THIS: move 16 Nov to 15:00 → becomes an exception
    await updateEvent(admin, occ[2].id, { ...weekly(), date: "2026-11-16", endDate: "2026-11-16", startTime: "15:00", endTime: "16:00" }, "THIS");
    // FOLLOWING from 23 Nov: rename
    await updateEvent(admin, occ[3].id, { ...weekly(), title: "Huddle v2", date: "2026-11-23", endDate: "2026-11-23" }, "FOLLOWING");
    let all = await db.internalEvent.findMany({ where: { id: { in: occ.map((o) => o.id) } }, orderBy: { startAt: "asc" } });
    expect(all.map((e) => e.title)).toEqual(["Weekly Huddle", "Weekly Huddle", "Weekly Huddle", "Huddle v2", "Huddle v2"]);
    expect(all[2].isException).toBe(true);
    expect(all[2].startAt.toISOString()).toBe("2026-11-16T08:00:00.000Z");
    // SERIES: topic change applies to future, non-exception occurrences only (2 Nov 13:00 is still upcoming)
    await updateEvent(admin, occ[1].id, { ...weekly(), topic: "Growth mindset", date: "2026-11-09", endDate: "2026-11-09" }, "SERIES");
    all = await db.internalEvent.findMany({ where: { id: { in: occ.map((o) => o.id) } }, orderBy: { startAt: "asc" } });
    expect(all.map((e) => e.topic)).toEqual(["Growth mindset", "Growth mindset", "Resilience", "Growth mindset", "Growth mindset"]);
    // series rule change Monday → Wednesday: Mondays cancelled (kept), Wednesdays created
    await updateEvent(admin, occ[1].id, { ...weekly(), date: "2026-11-09", endDate: "2026-11-09", recurrence: { freq: "WEEKLY", interval: 1, byWeekdays: [3], untilDate: "2026-11-30" } }, "SERIES");
    const active = await db.internalEvent.findMany({ where: { status: "PUBLISHED", title: { in: ["Weekly Huddle", "Huddle v2"] } }, orderBy: { startAt: "asc" } });
    expect(active.map((e) => e.localDate.toISOString().slice(0, 10))).toEqual(expect.arrayContaining(["2026-11-11", "2026-11-18", "2026-11-25", "2026-11-16"]));
    expect(await db.internalEvent.count({ where: { status: "CANCELLED", cancelReason: { contains: "recurrence" } } })).toBeGreaterThan(0);
    await expectError(updateEvent(admin, occ[2].id, { ...weekly(), date: "2026-11-16", endDate: "2026-11-16", recurrence: { freq: "DAILY", interval: 1, byWeekdays: [], untilDate: "2026-11-30" } }, "THIS"), "VALIDATION", /repeats/);
  });

  it("cancels one occurrence and keeps it for history", async () => {
    const admin = await org.actor("admin");
    const r = await createEvent(admin, weekly(), true);
    const occ = await db.internalEvent.findMany({ where: { seriesId: r.seriesId! }, orderBy: { startAt: "asc" } });
    await cancelEvent(admin, occ[1].id, "THIS", "Public speaking day instead");
    expect((await db.internalEvent.findUniqueOrThrow({ where: { id: occ[1].id } })).status).toBe("CANCELLED");
    expect(await db.internalEvent.count({ where: { seriesId: r.seriesId!, status: "PUBLISHED" } })).toBe(4);
    expect(await db.notification.count({ where: { type: "EVENT_CANCELLED" } })).toBeGreaterThan(0);
    expect(await db.internalEventAuditLog.count({ where: { eventId: occ[1].id, action: "CANCELLED" } })).toBe(1);
    await expect(db.internalEventAuditLog.deleteMany({})).rejects.toThrow(/append-only/);
  });

  it("drafts are visible to editors only and can be deleted; published events can't", async () => {
    const admin = await org.actor("admin");
    const d = await createEvent(admin, base({ title: "Secret draft" }), false);
    expect((await listEvents(await org.actor("junior"), "2026-11-01", "2026-11-30")).some((e) => e.id === d.id)).toBe(false);
    expect((await listEvents(admin, "2026-11-01", "2026-11-30")).some((e) => e.id === d.id)).toBe(true);
    await publishEvent(admin, d.id);
    await expectError(deleteDraft(admin, d.id), "INVALID_STATE");
    const d2 = await createEvent(admin, base({ title: "Another draft" }), false);
    expect((await deleteDraft(admin, d2.id)).deleted).toBe(1);
  });
});

describe("My Work Calendar integration", () => {
  it("shows assigned events and conflicts; approved schedules are never auto-changed", async () => {
    const ctx = await approve("junior");
    const wfh = ctx.requirement!.days.find((d) => d.plannable && !d.mandatory && d.date > "2026-11-03" && ctx.approvedModes[d.date] === "WFH")!.date;
    await createEvent(await org.actor("admin"), base({ title: "Gamification", date: wfh, endDate: wfh }), true);
    const after = await loadMonthContext(org.ids.junior, 2026, 11);
    expect(after.approvedModes[wfh]).toBe("WFH"); // unchanged
    const user = (await db.employee.findUniqueOrThrow({ where: { id: org.ids.junior } })).userId!;
    expect(await db.notification.count({ where: { userId: user, type: "EVENT_CONFLICT" } })).toBe(1);
    const data = await getPlannerData(await org.actor("junior"), org.ids.junior, 2026, 11);
    expect(data.days.find((d) => d.date === wfh)?.events[0]?.officeMandatory).toBe(true);
    expect(data.eventConflicts.map((c) => c.date)).toEqual([wfh]);
  });

  it("optional or remote-allowed events never create conflicts", async () => {
    const ctx = await approve("junior");
    const wfh = ctx.requirement!.days.find((d) => d.plannable && d.date > "2026-11-03" && ctx.approvedModes[d.date] === "WFH")!.date;
    await createEvent(await org.actor("admin"), base({ date: wfh, endDate: wfh, attendanceRequirement: "OPTIONAL" }), true);
    await createEvent(await org.actor("admin"), base({ date: wfh, endDate: wfh, wfoRequirement: "REMOTE_ALLOWED", locationType: "HYBRID", meetingUrl: "https://meet.example/abc" }), true);
    expect((await getPlannerData(await org.actor("junior"), org.ids.junior, 2026, 11)).eventConflicts).toHaveLength(0);
  });

  it("blocks submission with a WFH conflict until an exception is requested; the leader approves it", async () => {
    // principal: 50%, no mandatory weekdays → Tuesday 10 Nov can be WFH
    await createEvent(await org.actor("admin"), base({ title: "PitchLab", date: "2026-11-10", endDate: "2026-11-10" }), true);
    const p = await org.actor("principal");
    await autoGenerateDraft(p, { employeeId: p.employeeId, year: 2026, month: 11, mode: "generate" });
    expect((await loadMonthContext(p.employeeId, 2026, 11)).plannedModes["2026-11-10"]).toBe("WFO"); // auto-scheduling prioritised the event
    // swap: 10 Nov → WFH, another WFO day keeps the minimum
    const ctx = await loadMonthContext(p.employeeId, 2026, 11);
    const spare = ctx.requirement!.days.find((d) => d.plannable && ctx.plannedModes[d.date] === "WFH")!.date;
    await saveDraft(p, { employeeId: p.employeeId, year: 2026, month: 11, modes: { "2026-11-10": "WFH", [spare]: "WFO" } });
    await expectError(submitSchedule(p, { employeeId: p.employeeId, year: 2026, month: 11 }), "VALIDATION", /Schedule Conflict/);
    const ev = await db.internalEvent.findFirstOrThrow({ where: { title: "PitchLab" } });
    await requestConflictException(p, { eventId: ev.id, date: "2026-11-10", reason: "Client workshop at their office that morning" });
    await submitSchedule(p, { employeeId: p.employeeId, year: 2026, month: 11 });
    const leader = await org.actor("leader");
    const steps = await db.approvalStep.findMany({ where: { assigneeId: leader.employeeId, status: "PENDING" }, include: { workflow: true } });
    const exStep = steps.find((s) => s.workflow.subjectType === "EVENT_EXCEPTION")!;
    await decide(leader, exStep.id, "APPROVE", "OK this once");
    expect((await db.internalEventConflictException.findFirstOrThrow()).status).toBe("APPROVED");
  });

  it("a revision to WFH on a mandatory in-office event date needs an exception", async () => {
    const ctx = await approve("principal");
    const wfoDay = ctx.requirement!.days.find((d) => d.plannable && d.date > "2026-11-03" && ctx.approvedModes[d.date] === "WFO")!.date;
    const wfhDay = ctx.requirement!.days.find((d) => d.plannable && d.date > "2026-11-03" && ctx.approvedModes[d.date] === "WFH")!.date;
    await createEvent(await org.actor("admin"), base({ title: "ATLAS Demo", date: wfoDay, endDate: wfoDay }), true);
    const p = await org.actor("principal");
    const input = { employeeId: p.employeeId, year: 2026, month: 11, kind: "SWAP" as const, changes: [{ date: wfoDay, toMode: "WFH" as const }, { date: wfhDay, toMode: "WFO" as const }], reason: "Need a quiet day for analysis", idempotencyKey: key() };
    await expectError(createRevision(p, input), "VALIDATION", /Schedule Conflict/);
    const rev = await createRevision(p, { ...input, requestException: true });
    expect(rev.requiresException).toBe(true);
    await decide(await org.actor("leader"), (await pendingStepFor(org.ids.leader))!.id, "APPROVE");
    expect(await db.internalEventConflictException.count({ where: { status: "APPROVED" } })).toBe(1);
  });

  it("cancelling an event removes the conflict", async () => {
    const ctx = await approve("junior");
    const wfh = ctx.requirement!.days.find((d) => d.plannable && d.date > "2026-11-03" && ctx.approvedModes[d.date] === "WFH")!.date;
    const r = await createEvent(await org.actor("admin"), base({ date: wfh, endDate: wfh }), true);
    await cancelEvent(await org.actor("admin"), r.id, "THIS", "Postponed");
    expect((await getPlannerData(await org.actor("junior"), org.ids.junior, 2026, 11)).eventConflicts).toHaveLength(0);
  });
});

describe("reminders", () => {
  it("sends due reminders once per offset", async () => {
    await createEvent(await org.actor("admin"), base({ date: "2026-11-03", endDate: "2026-11-03" }), true);
    const people = await db.employee.count({ where: { isActive: true } });
    expect((await sendDueReminders(new Date("2026-11-02T03:00:00Z"))).sent).toBe(people); // 1 day before has passed
    await sendDueReminders(new Date("2026-11-02T04:00:00Z"));
    expect(await db.notification.count({ where: { type: "EVENT_REMINDER" } })).toBe(people); // deduplicated
    await sendDueReminders(new Date("2026-11-03T01:30:00Z")); // 08:30 WIB → 1-hour reminder
    expect(await db.notification.count({ where: { type: "EVENT_REMINDER" } })).toBe(people * 2);
  });
});

describe("holidays and off days", () => {
  it("rejects a one-time event on a holiday unless explicitly allowed", async () => {
    const admin = await org.actor("admin");
    await expectError(createEvent(admin, base({ date: "2026-12-25", endDate: "2026-12-25" }), true), "VALIDATION", /holiday \(Natal\)/);
    const r = await createEvent(admin, base({ title: "Christmas gathering", date: "2026-12-25", endDate: "2026-12-25", allowOnOffDays: true }), true);
    expect(r.occurrences).toBe(1);
  });

  it("skips holidays and non-working days in recurring series", async () => {
    const admin = await org.actor("admin");
    const fridays = await createEvent(admin, base({ date: "2026-12-04", endDate: "2026-12-04", recurrence: { freq: "WEEKLY", interval: 1, byWeekdays: [5], untilDate: "2026-12-31" } }), true);
    expect(fridays.occurrences).toBe(3); // 25 Dec (Natal) skipped
    expect(fridays.skipped.map((x) => x.date)).toEqual(["2026-12-25"]);
    const daily = await createEvent(admin, base({ date: "2026-11-06", endDate: "2026-11-06", recurrence: { freq: "DAILY", interval: 1, byWeekdays: [], untilDate: "2026-11-10" } }), true);
    expect(daily.occurrences).toBe(3); // Sat & Sun skipped
  });

  it("adding a holiday later cancels events on that date and notifies participants", async () => {
    const { upsertHoliday } = await import("@/server/services/admin");
    const admin = await org.actor("admin");
    const normal = await createEvent(admin, base({ title: "Retail Insights", date: "2026-11-20", endDate: "2026-11-20" }), true);
    const allowed = await createEvent(admin, base({ title: "Holiday hackathon", date: "2026-11-20", endDate: "2026-11-20", allowOnOffDays: true }), true);
    const h = await upsertHoliday(admin, { date: "2026-11-20", name: "Company retreat day", type: "COMPANY", isObserved: true });
    expect(h.eventsCancelled).toBe(1);
    const e = await db.internalEvent.findUniqueOrThrow({ where: { id: normal.id } });
    expect(e.status).toBe("CANCELLED");
    expect(e.cancelReason).toMatch(/Company retreat day/);
    expect((await db.internalEvent.findUniqueOrThrow({ where: { id: allowed.id } })).status).toBe("PUBLISHED");
    expect(await db.notification.count({ where: { type: "EVENT_CANCELLED", body: { contains: "Company retreat day" } } })).toBeGreaterThan(0);
    // cancelled events are hidden from the calendar by default
    expect((await listEvents(admin, "2026-11-01", "2026-11-30")).some((x) => x.id === normal.id)).toBe(false);
  });
});
