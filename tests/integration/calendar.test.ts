async function expectError(p: Promise<unknown>, code: DomainError["code"], msg?: RegExp) {
  try {
    await p;
  } catch (e) {
    expect(e).toBeInstanceOf(DomainError);
    expect((e as DomainError).code).toBe(code);
    if (msg) expect((e as DomainError).message).toMatch(msg);
    return e as DomainError;
  }
  throw new Error(`Expected ${code}`);
}

const base = (over: Partial<EventInput> = {}): EventInput => ({
  title: "Weekly Huddle",
  categoryId,
  topic: "Resilience",
  description: "Demo time — not confirmed",
  date: "2026-11-10",
  startTime: "09:00",
  endDate: "2026-11-10",
  endTime: "10:00",
  locationType: "IN_OFFICE",
  locationDetail: "MIL office, main room",
  meetingUrl: null,
  organizerId: org.ids.admin,
  attendanceRequirement: "MANDATORY",
  wfoRequirement: "IN_OFFICE_REQUIRED",
  reminderMinutes: [1440, 60],
  rules: [{ type: "ALL", targetId: null, dynamic: false }],
  recurrence: { freq: "NONE", interval: 1, byWeekdays: [], untilDate: "2026-11-10" },
  ...over,
});

async function approve(who: string, year = 2026, month = 11) {
  const a = await org.actor(who);
  await autoGenerateDraft(a, { employeeId: a.employeeId, year, month, mode: "generate" });
  await submitSchedule(a, { employeeId: a.employeeId, year, month });
  const leader = await org.actor("leader");
  await decide(leader, (await pendingStepFor(leader.employeeId))!.id, "APPROVE");
  return loadMonthContext(a.employeeId, year, month);
}

