// WFO Policy off: the Super Admin's office schedule drives every calendar.
// "Today" is frozen at Monday 2 November 2026, 10:00 WIB.
import { afterAll, beforeAll, beforeEach, describe, expect, it, vi } from "vitest";
import { db, withTx } from "@/server/db";
import { DomainError } from "@/server/errors";
import { getPlannerData, autoGenerateDraft, submitSchedule } from "@/server/services/schedules";
import { decide } from "@/server/services/approvals";
import { createRevision } from "@/server/services/revisions";
import { loadMonthContext } from "@/server/services/calendar";
import { freezePastDays, setOfficeDays, setOfficePattern, setWfoPolicyEnabled } from "@/server/services/office";
import { runDailyJobs } from "@/server/services/jobs";
import { buildOrg, key, pendingStepFor, resetDb, type Org } from "./helpers";

let org: Org;

async function expectError(p: Promise<unknown>, code: DomainError["code"], msg?: RegExp) {
  try {
    await p;
  } catch (e) {
    expect(e).toBeInstanceOf(DomainError);
    expect((e as DomainError).code).toBe(code);
    if (msg) expect((e as DomainError).message).toMatch(msg);
    return;
  }
  throw new Error(`Expected ${code} error`);
}

/** Company office days Tue + Thu, WFO Policy off. */
async function officeMode() {
  const admin = await org.actor("admin");
  await setOfficePattern(admin, { teamId: null, wfoWeekdays: [2, 4] });
  await setWfoPolicyEnabled(admin, false);
  return admin;
}

const modes = async (who: string, month = 11) => (await loadMonthContext(org.ids[who], 2026, month)).approvedModes;

beforeAll(() => {
  vi.useFakeTimers({ toFake: ["Date"], now: new Date("2026-11-02T03:00:00Z") });
});
afterAll(async () => {
  vi.useRealTimers();
  await db.$disconnect();
});
beforeEach(async () => {
  vi.setSystemTime(new Date("2026-11-02T03:00:00Z"));
  await resetDb();
  org = await buildOrg();
});

describe("WFO Policy switch", () => {
  it("needs the company's office days before it can be turned off", async () => {
    const admin = await org.actor("admin");
    await expectError(setWfoPolicyEnabled(admin, false), "INVALID_STATE", /weekly office days/);
    await expectError(setWfoPolicyEnabled(await org.actor("hr"), false), "FORBIDDEN");
  });

  it("makes calendars follow the office schedule with no WFO target or plan to submit", async () => {
    await officeMode();
    const m = await modes("junior");
    expect(m["2026-11-02"]).toBe("WFH"); // Monday
    expect(m["2026-11-03"]).toBe("WFO"); // Tuesday
    expect(m["2026-11-05"]).toBe("WFO"); // Thursday
    const junior = await org.actor("junior");
    const data = await getPlannerData(junior, junior.employeeId, 2026, 11);
    expect(data.officeMode).toBe(true);
    expect(data.officeWeekdays).toEqual([2, 4]);
    expect(data.canEdit).toBe(false);
    expect(data.canRevise).toBe(true);
    expect(data.requirement!.effectiveMinimumWfo).toBe(0);
    expect(data.days.some((d) => d.mandatory)).toBe(false);
    await expectError(submitSchedule(junior, { employeeId: junior.employeeId, year: 2026, month: 11 }), "INVALID_STATE", /office schedule/);
    // viewing the calendar never creates a draft plan
    expect(await db.monthlySchedule.count()).toBe(0);
  });

  it("keeps days before the switch as they were under the WFO Policy", async () => {
    const junior = await org.actor("junior");
    await autoGenerateDraft(junior, { employeeId: junior.employeeId, year: 2026, month: 11, mode: "generate" });
    await submitSchedule(junior, { employeeId: junior.employeeId, year: 2026, month: 11 });
    const leader = await org.actor("leader");
    await decide(leader, (await pendingStepFor(leader.employeeId))!.id, "APPROVE");
    const before = await modes("junior");
    expect(before["2026-11-02"]).toBe("WFO"); // Monday is a mandatory day for juniors

    vi.setSystemTime(new Date("2026-11-05T03:00:00Z"));
    await officeMode();
    const after = await modes("junior");
    expect(after["2026-11-02"]).toBe("WFO"); // past: unchanged
    expect(after["2026-11-04"]).toBe(before["2026-11-04"]);
    expect(after["2026-11-09"]).toBe("WFH"); // from today on: office schedule (Monday is not an office day)
    expect(after["2026-11-10"]).toBe("WFO");
  });
});

describe("Turning the WFO Policy back on", () => {
  it("keeps the office schedule as each employee's approved plan", async () => {
    const admin = await officeMode();
    const junior = await org.actor("junior");
    await createRevision(junior, { employeeId: junior.employeeId, year: 2026, month: 11, kind: "WFH_TO_WFO", changes: [{ date: "2026-11-04", toMode: "WFO" }], reason: "", idempotencyKey: key() });
    await setWfoPolicyEnabled(admin, true);
    const ctx = await loadMonthContext(junior.employeeId, 2026, 11);
    expect(ctx.office).toBeNull();
    expect(ctx.schedule?.status).toBe("APPROVED");
    expect(ctx.approvedModes["2026-11-03"]).toBe("WFO");
    expect(ctx.approvedModes["2026-11-04"]).toBe("WFO");
    expect(ctx.approvedModes["2026-11-09"]).toBe("WFH");
    expect(Object.keys(ctx.approvedModes)).toHaveLength(21);
    expect(Object.keys((await loadMonthContext(junior.employeeId, 2026, 12)).approvedModes).length).toBeGreaterThan(0);
  });
});

describe("Office schedule set by the Super Admin", () => {
  it("applies team weekly days, company closures and team overrides in that order", async () => {
    const admin = await officeMode();
    const team = await db.team.findFirstOrThrow();
    await setOfficePattern(admin, { teamId: team.id, wfoWeekdays: [1, 3] });
    await setOfficeDays(admin, { teamId: null, dates: ["2026-11-09"], mode: "WFH", note: "Office closed for maintenance" });
    await setOfficeDays(admin, { teamId: team.id, dates: ["2026-11-12"], mode: "WFO", note: "Quarterly planning" });
    const ctx = await loadMonthContext(org.ids.junior, 2026, 11);
    expect(ctx.approvedModes["2026-11-02"]).toBe("WFO"); // team Monday
    expect(ctx.approvedModes["2026-11-03"]).toBe("WFH"); // company Tuesday no longer applies to this team
    expect(ctx.approvedModes["2026-11-09"]).toBe("WFH");
    expect(ctx.office!["2026-11-09"].note).toBe("Office closed for maintenance");
    expect(ctx.approvedModes["2026-11-12"]).toBe("WFO");
    expect(ctx.office!["2026-11-12"]).toMatchObject({ note: "Quarterly planning", scope: "TEAM" });
    // back to the usual days
    await setOfficeDays(admin, { teamId: team.id, dates: ["2026-11-12"], mode: null });
    expect((await modes("junior"))["2026-11-12"]).toBe("WFH");
    await setOfficePattern(admin, { teamId: team.id, wfoWeekdays: null });
    expect((await modes("junior"))["2026-11-03"]).toBe("WFO");
  });

  it("rejects past dates, non-working weekdays and non-admins", async () => {
    const admin = await officeMode();
    await expectError(setOfficeDays(admin, { teamId: null, dates: ["2026-10-30"], mode: "WFH" }), "VALIDATION", /Past dates/);
    await expectError(setOfficePattern(admin, { teamId: null, wfoWeekdays: [6] }), "VALIDATION", /not a working day/);
    await expectError(setOfficeDays(await org.actor("leader"), { teamId: null, dates: ["2026-11-10"], mode: "WFH" }), "FORBIDDEN");
  });

  it("never rewrites days that have passed when the weekly days change", async () => {
    const admin = await officeMode();
    vi.setSystemTime(new Date("2026-11-05T03:00:00Z"));
    await setOfficePattern(admin, { teamId: null, wfoWeekdays: [1] });
    const m = await modes("junior");
    expect(m["2026-11-03"]).toBe("WFO"); // past Tuesday kept
    expect(m["2026-11-02"]).toBe("WFH"); // past Monday kept
    expect(m["2026-11-09"]).toBe("WFO");
    expect(m["2026-11-10"]).toBe("WFH");
  });
});

describe("Employee changes in office schedule mode", () => {
  it("applies an extra office day at once, with the note on the day", async () => {
    await officeMode();
    const junior = await org.actor("junior");
    const rev = await createRevision(junior, { employeeId: junior.employeeId, year: 2026, month: 11, kind: "WFH_TO_WFO", changes: [{ date: "2026-11-04", toMode: "WFO" }], reason: "Client meeting", idempotencyKey: key() });
    expect(rev.status).toBe("APPROVED");
    const ctx = await loadMonthContext(junior.employeeId, 2026, 11);
    expect(ctx.approvedModes["2026-11-04"]).toBe("WFO");
    expect(ctx.dayNotes["2026-11-04"]).toBe("Client meeting");
    expect(await db.approvalWorkflow.count()).toBe(0);
    // the note is optional
    const r2 = await createRevision(junior, { employeeId: junior.employeeId, year: 2026, month: 11, kind: "WFH_TO_WFO", changes: [{ date: "2026-11-06", toMode: "WFO" }], reason: "", idempotencyKey: key() });
    expect(r2.status).toBe("APPROVED");
  });

  it("sends WFO → WFH to the leader and applies it on approval", async () => {
    await officeMode();
    const junior = await org.actor("junior");
    await expectError(
      createRevision(junior, { employeeId: junior.employeeId, year: 2026, month: 11, kind: "WFO_TO_WFH", changes: [{ date: "2026-11-10", toMode: "WFH" }], reason: "home", idempotencyKey: key() }),
      "VALIDATION",
      /at least 10/,
    );
    const rev = await createRevision(junior, { employeeId: junior.employeeId, year: 2026, month: 11, kind: "WFO_TO_WFH", changes: [{ date: "2026-11-10", toMode: "WFH" }], reason: "Waiting for a home repair", idempotencyKey: key() });
    expect(rev.status).toBe("PENDING");
    expect((await modes("junior"))["2026-11-10"]).toBe("WFO"); // unchanged until approved
    const leader = await org.actor("leader");
    await decide(leader, (await pendingStepFor(leader.employeeId))!.id, "APPROVE");
    expect((await modes("junior"))["2026-11-10"]).toBe("WFH");
    const schedule = await db.monthlySchedule.findFirstOrThrow({ where: { employeeId: junior.employeeId } });
    expect(schedule.status).toBe("APPROVED");
  });

  it("splits a mixed request: the office day applies now, the WFH day waits for the leader", async () => {
    await officeMode();
    const junior = await org.actor("junior");
    const k = key();
    const rev = await createRevision(junior, {
      employeeId: junior.employeeId,
      year: 2026,
      month: 11,
      kind: "SWAP",
      changes: [
        { date: "2026-11-11", toMode: "WFO" },
        { date: "2026-11-12", toMode: "WFH" },
      ],
      reason: "Swapping office day this week",
      idempotencyKey: k,
    });
    expect(rev.status).toBe("PENDING");
    const m = await modes("junior");
    expect(m["2026-11-11"]).toBe("WFO");
    expect(m["2026-11-12"]).toBe("WFO");
    // a retry returns the same request
    const again = await createRevision(junior, { employeeId: junior.employeeId, year: 2026, month: 11, kind: "SWAP", changes: [{ date: "2026-11-12", toMode: "WFH" }], reason: "Swapping office day this week", idempotencyKey: k });
    expect(again.id).toBe(rev.id);
  });

  it("lets a later office schedule change replace the employee's own change, and tells them", async () => {
    const admin = await officeMode();
    const junior = await org.actor("junior");
    await createRevision(junior, { employeeId: junior.employeeId, year: 2026, month: 11, kind: "WFH_TO_WFO", changes: [{ date: "2026-11-04", toMode: "WFO" }], reason: "Client meeting", idempotencyKey: key() });
    await setOfficeDays(admin, { teamId: null, dates: ["2026-11-04"], mode: "WFH", note: "Office closed" });
    const ctx = await loadMonthContext(junior.employeeId, 2026, 11);
    expect(ctx.approvedModes["2026-11-04"]).toBe("WFH");
    expect(ctx.dayNotes["2026-11-04"]).toBeUndefined();
    const n = await db.notification.findFirst({ where: { user: { employee: { id: junior.employeeId } }, type: "OFFICE_SCHEDULE_CHANGED" } });
    expect(n?.body).toMatch(/Office closed/);
    // an unrelated date keeps the employee's own change
    await createRevision(junior, { employeeId: junior.employeeId, year: 2026, month: 11, kind: "WFH_TO_WFO", changes: [{ date: "2026-11-06", toMode: "WFO" }], reason: "", idempotencyKey: key() });
    await setOfficeDays(admin, { teamId: null, dates: ["2026-11-10"], mode: "WFH", note: "Office closed" });
    expect((await modes("junior"))["2026-11-06"]).toBe("WFO");
  });
});

describe("Daily jobs in office schedule mode", () => {
  it("sends no plan reminders, prepares no drafts and freezes days that have passed", async () => {
    await officeMode();
    vi.setSystemTime(new Date("2026-11-04T01:00:00Z"));
    const r = await runDailyJobs();
    expect(r.reminders).toBe(0);
    expect(r.plansPrefilled).toBe(0);
    expect(r.officeDaysFrozen).toBeGreaterThan(0);
    expect(await db.monthlySchedule.count({ where: { status: "DRAFT" } })).toBe(0);
    const frozen = await db.scheduleDay.findMany({ where: { frozen: true, schedule: { employeeId: org.ids.junior, month: 11 } } });
    expect(frozen.map((d) => d.date.toISOString().slice(0, 10)).sort()).toEqual(["2026-11-02", "2026-11-03"]);
    // running it again changes nothing
    expect(await withTx((tx) => freezePastDays(tx, "2026-11-03"))).toBe(0);
  });
});
